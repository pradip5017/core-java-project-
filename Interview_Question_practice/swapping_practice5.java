package Interview_Question_practice;

public class swapping_practice5 {
	public static void main(String args[])
	{
		// swapping of data swap to a=20 to b =10
		int a=10; 
		int b=20;
		
		a=a +b; // a=  30
		b= a-b; // b = 10
		a=a-b;  // a = 20 
		
		System.out.println("A :"+a);
		System.out.println("B :"+b);
		
		
	}

}
